"""
make_ch1_tables.py — генерация LaTeX-таблиц tab1_1 и tab1_2 для главы 1 ВКР.

tab1_1 — Сравнение существующих инструментов и предлагаемой системы.
tab1_2 — Требования к разрабатываемой системе (6 функциональных + 4 нефункциональных).

Usage:
    python scripts/make_ch1_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from csv_to_latex_table import df_to_latex_booktabs  # noqa: E402


OUT_DIR = ROOT / "vkr" / "v2" / "artifacts" / "tables"


def build_tab1_1() -> Path:
    """Сравнение инструментов: транспонированная компоновка (capabilities × tools).

    Использует словесные значения «да», «нет», «частично», «вручную» —
    компилируется в любом LaTeX-движке без зависимости от UTF-символов
    галочки/крестика.
    """
    comparison = pd.DataFrame({
        "capability": [
            "Описание текущего состояния продукта",
            "Прогноз метрик на горизонт вперёд",
            "Сценарии «что, если» по управляемым метрикам",
            "Объяснение модели через вклад признаков",
            "Рекомендации управляемых действий",
            "Итоговый вердикт по продукту",
        ],
        "ga_firebase": ["да", "нет", "нет", "нет", "нет", "нет"],
        "mixpanel": ["да", "частично", "нет", "частично", "нет", "нет"],
        "tableau": ["да", "нет", "нет", "нет", "нет", "нет"],
        "excel": ["да", "вручную", "вручную", "вручную", "вручную", "вручную"],
        "proposed": ["да", "да", "да", "да", "да", "да"],
    })

    out_path = OUT_DIR / "tab1_1.tex"
    caption = (
        "Сравнение существующих инструментов продуктовой аналитики и предлагаемой системы. "
        "Существующие инструменты дают описание текущего состояния, но не покрывают цепочку "
        "прогноз — сценарии — рекомендации — вердикт в едином воспроизводимом расчёте."
    )
    df_to_latex_booktabs(
        comparison,
        out_path,
        columns={
            "capability": "Возможность",
            "ga_firebase": "Google Analytics, Firebase",
            "mixpanel": "Mixpanel, Amplitude",
            "tableau": "Tableau, Power BI",
            "excel": "Excel плюс Python",
            "proposed": "Предлагаемая система",
        },
        caption=caption,
        label="tab:ch1_tools",
        alignment="p{4.6cm}p{2.3cm}p{2.0cm}p{2.0cm}p{1.9cm}p{2.1cm}",
    )
    return out_path


def build_tab1_2() -> Path:
    """Требования к системе: 6 функциональных + 4 нефункциональных, с обоснованиями."""
    requirements = pd.DataFrame({
        "num": list(range(1, 11)),
        "requirement": [
            "Прогноз ключевых метрик продукта на горизонт до 14 дней",
            "Оценка надёжности прогноза (доверительные интервалы)",
            "Сценарный анализ «что, если» по управляемым метрикам",
            "Объяснение прогноза через вклад признаков",
            "Рекомендации управляемых действий",
            "Итоговый вердикт по продукту (развивать, мониторить, закрывать)",
            "Воспроизводимость расчётов (фиксированные параметры)",
            "Web-интерфейс для пользователя без программирования",
            "Запуск на стандартном персональном компьютере без специализированного оборудования",
            "Прозрачность результатов: реестр с проверкой целостности",
        ],
        "type": [
            "Функциональное",
            "Функциональное",
            "Функциональное",
            "Функциональное",
            "Функциональное",
            "Функциональное",
            "Нефункциональное",
            "Нефункциональное",
            "Нефункциональное",
            "Нефункциональное",
        ],
        "rationale": [
            "Аналитик получает горизонт планирования вперёд, не дожидаясь новых наблюдений",
            "Без интервала невозможно отличить надёжный прогноз от шума",
            "Управленческие решения требуют ответа на вопрос «а если изменим вот это?»",
            "Без объяснения прогноз становится непрозрачным, а рекомендации необоснованными",
            "Аналитик получает конкретные действия, а не абстрактные оценки",
            "Руководителю нужно одно решение, а не таблица метрик",
            "Защита от случайности: повторный запуск даёт идентичный результат",
            "Целевой пользователь — аналитик, не программист",
            "Низкий порог входа, развёртывание на ноутбуке за минуты",
            "Любой результат можно проверить по цепочке источников",
        ],
    })

    out_path = OUT_DIR / "tab1_2.tex"
    caption = (
        "Требования к разрабатываемой системе: шесть функциональных (что система делает) "
        "и четыре нефункциональных (как и для кого). Каждое требование сопровождается "
        "обоснованием, чтобы было ясно, какую пользовательскую боль оно закрывает."
    )
    df_to_latex_booktabs(
        requirements,
        out_path,
        columns={
            "num": "№",
            "requirement": "Требование",
            "type": "Тип",
            "rationale": "Обоснование",
        },
        caption=caption,
        label="tab:ch1_requirements",
        alignment="rp{5.6cm}p{2.4cm}p{5.4cm}",
    )
    return out_path


def main() -> None:
    p1 = build_tab1_1()
    p2 = build_tab1_2()
    print(f"OK tab1_1 -> {p1}")
    print(f"OK tab1_2 -> {p2}")


if __name__ == "__main__":
    main()
